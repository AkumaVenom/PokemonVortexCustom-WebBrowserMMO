function pv_wild_damage(array $attacker, array $defender, array $move): array
{
    $accuracy = max(1, min(100, (int)($move['accuracy'] ?? 100)));
    if (random_int(1,100) > $accuracy) {
        return ['damage'=>0,'hit'=>false,'critical'=>false,'effectiveness'=>1.0];
    }
    $power = max(0, (int)($move['power'] ?? 0));
    if ($power <= 0) {
        return ['damage'=>0,'hit'=>true,'critical'=>false,'effectiveness'=>1.0];
    }

    $level = max(1, (int)($attacker['level'] ?? 1));
    $type = (string)($move['type'] ?? 'Normal');
    $stab = (strcasecmp($type, (string)($attacker['type1'] ?? '')) === 0 || strcasecmp($type, (string)($attacker['type2'] ?? '')) === 0) ? 1.5 : 1.0;
    $effectiveness = pv_wild_type_effectiveness($type, (string)($defender['type1'] ?? ''))
        * pv_wild_type_effectiveness($type, (string)($defender['type2'] ?? ''));
    $critical = random_int(1,16) === 1;
    $crit = $critical ? 1.5 : 1.0;
    $variance = random_int(85,100) / 100;
    $base = (((2 * $level / 5) + 2) * $power / 50) + 2;
    $damage = $effectiveness <= 0.0 ? 0 : max(1, (int)floor($base * $stab * $effectiveness * $crit * $variance));
    return ['damage'=>$damage,'hit'=>true,'critical'=>$critical,'effectiveness'=>$effectiveness];
}

