function pv_wild_consume(mysqli $db, int $uid, string $column): bool
{
    $allowed=['potion','super_potion','hyper_potion','poke_ball','great_ball','ultra_ball','master_ball'];
    if(!in_array($column,$allowed,true)) return false;
    $sql='UPDATE items SET `'.$column.'`=`'.$column.'`-1 WHERE uid=? AND `'.$column.'`>0';
    $stmt=$db->prepare($sql); if(!$stmt) return false;
    $stmt->bind_param('i',$uid);$ok=$stmt->execute() && $stmt->affected_rows===1;$stmt->close();
    return $ok;
}

function pv_wild_use_heal(mysqli $db, array &$state, string $item): void
{
    $catalog=pv_wild_item_catalog();
    if(!isset($catalog[$item])) throw new RuntimeException('Choose a valid battle medicine.');
    $activeId=(int)$state['active_id'];
    $player =& $state['team'][$activeId];
    if((int)$player['hp']<=0) throw new RuntimeException('A fainted Pokémon cannot use battle medicine.');
    if((int)$player['hp']>=(int)$player['max_hp']) throw new RuntimeException($player['name'].' is already at full HP.');
    if(!pv_wild_consume($db,(int)$_SESSION['myid'],$catalog[$item]['column'])) throw new RuntimeException('You do not have that item in your inventory.');
    $before=(int)$player['hp'];
    $player['hp']=min((int)$player['max_hp'],$before+(int)$catalog[$item]['heal']);
    $state['fx']['heal']=['item'=>$item,'amount'=>(int)($player['hp']-$before)];
    pv_wild_log($state,'You used '.$item.'. '.$player['name'].' recovered '.($player['hp']-$before).' HP.','good');
    pv_wild_enemy_turn($db,$state);
}

function pv_wild_gender(string $name): string
{
    $plain=preg_replace('/^(Shiny|Dark|Mystic|Shadow|Metallic)\s+/i','',$name) ?: $name;
