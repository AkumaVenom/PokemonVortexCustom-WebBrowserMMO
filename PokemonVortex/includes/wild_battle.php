function pv_wild_team(mysqli $db, int $uid): array
{
    $stmt = $db->prepare('SELECT s1,s2,s3,s4,s5,s6 FROM members WHERE id=? LIMIT 1');
    if (!$stmt) return [];
    $stmt->bind_param('i',$uid);
    $stmt->execute();
    $slots = $stmt->get_result()->fetch_assoc() ?: [];
    $stmt->close();

    $team = [];
    for ($slot=1; $slot<=6; $slot++) {
        $id = (int)($slots['s'.$slot] ?? 0);
        if ($id <= 0) continue;
        $stmt = $db->prepare('SELECT p.id,p.pid,p.name,p.a1,p.a2,p.a3,p.a4,p.lvl,p.t1,p.t2,COALESCE(ps.hp_iv,0) hp_iv FROM pokemon p LEFT JOIN pokemon_stats ps ON ps.id=p.id WHERE p.id=? AND CAST(p.owner AS UNSIGNED)=? LIMIT 1');
        if (!$stmt) continue;
        $stmt->bind_param('ii',$id,$uid);
        $stmt->execute();
        $row = $stmt->get_result()->fetch_assoc();
        $stmt->close();
        if (!$row) continue;
        $name=(string)$row['name']; $level=max(1,(int)$row['lvl']);
        $maxHp=pv_wild_hp_max($name,$level,(int)$row['hp_iv']);
        $team[$id]=[
            'id'=>$id,'pid'=>(int)$row['pid'],'name'=>$name,'display_name'=>$name,'sprite_name'=>$name,
            'level'=>$level,'type1'=>(string)$row['t1'],'type2'=>(string)$row['t2'],
            'moves'=>array_values(array_filter([(string)$row['a1'],(string)$row['a2'],(string)$row['a3'],(string)$row['a4']], static fn($v)=>trim($v)!=='')),
            'max_hp'=>$maxHp,'hp'=>$maxHp,'status'=>'none','slot'=>$slot,
        ];
    }
    return $team;
}

function pv_wild_start(mysqli $db, int $uid, string $token): array
{
    $pending = $_SESSION['pv_pending_wild_encounter'] ?? null;
    if (!is_array($pending) || !hash_equals((string)($pending['token'] ?? ''), $token)) {
        throw new RuntimeException('That wild encounter is no longer active. Move again on the map to scan for another Pokémon.');
    }
    if (!empty($pending['consumed']) || (time() - (int)($pending['created_at'] ?? 0)) > 900) {
        unset($_SESSION['pv_pending_wild_encounter']);
        throw new RuntimeException('That wild signal has expired. Return to the map and scan again.');
    }

    $pid=(int)($pending['pid'] ?? 0);
    $stmt=$db->prepare('SELECT id,name,type1,type2,a1,a2,a3,a4 FROM pguide WHERE id=? LIMIT 1');
    if(!$stmt) throw new RuntimeException('Wild Pokémon data is temporarily unavailable.');
    $stmt->bind_param('i',$pid); $stmt->execute(); $guide=$stmt->get_result()->fetch_assoc(); $stmt->close();
    if(!$guide) throw new RuntimeException('This wild Pokémon is not available for battle right now. Return to the map and scan again.');

    $team=pv_wild_team($db,$uid);
    if(!$team) throw new RuntimeException('Add at least one Pokémon to your active team before starting a wild battle.');
    $activeId=(int)array_key_first($team);
    $level=pv_wild_authoritative_encounter_level($pending);
    $canonical=(string)$guide['name'];
    $display=trim((string)($pending['display_name'] ?? $canonical)) ?: $canonical;
    $sprite=trim((string)($pending['sprite_name'] ?? $display)) ?: $canonical;
    $maxHp=pv_wild_hp_max($canonical,$level,random_int(0,31));
    $wild=[
        'pid'=>(int)$guide['id'],'name'=>$canonical,'display_name'=>$display,'sprite_name'=>$sprite,'level'=>$level,
        'type1'=>(string)$guide['type1'],'type2'=>(string)$guide['type2'],
        'moves'=>array_values(array_filter([(string)$guide['a1'],(string)$guide['a2'],(string)$guide['a3'],(string)$guide['a4']], static fn($v)=>trim($v)!=='')),
        'max_hp'=>$maxHp,'hp'=>$maxHp,'status'=>'none',
    ];
    if(!$wild['moves']) $wild['moves']=['Tackle'];

    $state=[
        'id'=>bin2hex(random_bytes(16)),'status'=>'active','created_at'=>time(),'updated_at'=>time(),'turn'=>1,
        'map'=>max(0,min(25,(int)($pending['map'] ?? ($_SESSION['map'] ?? 1)))),
        'world'=>trim((string)($pending['world']??'vortex'))?:'vortex',
        'area'=>trim((string)($pending['area']??'')),
        'encounter_token'=>$token,'wild'=>$wild,'team'=>$team,'active_id'=>$activeId,
        'participants'=>[$activeId=>true],'log'=>[],'result'=>null,'rewarded'=>false,
        'fx'=>['id'=>bin2hex(random_bytes(6)),'turn'=>0,'action'=>'intro','detail'=>'','player'=>null,'enemy'=>null,'capture'=>null,'heal'=>null,'switch'=>null,'created_at'=>time()],
    ];
    pv_wild_log($state,'Wild '.$display.' appeared at level '.$level.'.','accent');
    pv_wild_log($state,'Go, '.$team[$activeId]['name'].'!');
    pv_admin_world_claim_spawn($db,$uid,$pending);
    $_SESSION['pv_pending_wild_encounter']['consumed']=true;
    pv_wild_save($state);
    return $state;
}

function pv_wild_effectiveness_text(float $value): string
{
    if ($value <= 0.0) return ' It had no effect.';
    if ($value >= 2.0) return " It's super effective!";
    if ($value < 1.0) return " It's not very effective.";
    return '';
}

function pv_wild_attack_turn(mysqli $db, array &$state, int $attackerId, string $moveName): void
{
    if (($state['status'] ?? '') !== 'active') return;
    if (!isset($state['team'][$attackerId]) || $attackerId !== (int)$state['active_id']) return;
    $player =& $state['team'][$attackerId];
    $wild =& $state['wild'];
    if ((int)$player['hp'] <= 0 || (int)$wild['hp'] <= 0) return;

    if (!in_array($moveName,$player['moves'],true)) throw new RuntimeException('Choose one of your active Pokémon’s moves.');
    $move=pv_wild_move_data($db,$moveName,(string)$player['type1']);
    $result=pv_wild_damage($player,$wild,$move);
    $state['fx']['player']=[
        'move'=>(string)$move['attack'],'type'=>(string)$move['type'],'hit'=>(bool)$result['hit'],
        'damage'=>(int)$result['damage'],'critical'=>(bool)$result['critical'],'effectiveness'=>(float)$result['effectiveness'],
    ];
    if(!$result['hit']) {
        pv_wild_log($state,$player['name'].' used '.$move['attack'].', but it missed.','muted');
    } else {
        $wild['hp']=max(0,(int)$wild['hp']-(int)$result['damage']);
        $msg=$player['name'].' used '.$move['attack'].' and dealt '.(int)$result['damage'].' damage.';
        if($result['critical']) $msg.=' Critical hit!';
        $msg.=pv_wild_effectiveness_text((float)$result['effectiveness']);
        pv_wild_log($state,$msg,$result['effectiveness']>=2?'good':'neutral');
    }
    if((int)$wild['hp']<=0){
        $state['fx']['enemy_fainted']=true;
        pv_wild_finalize_win($db,$state);
        return;
    }
    pv_wild_enemy_turn($db,$state);
}

function pv_wild_enemy_turn(mysqli $db, array &$state): void
{
    if (($state['status'] ?? '') !== 'active') return;
    $activeId=(int)$state['active_id'];
    if(!isset($state['team'][$activeId])) return;
    $player =& $state['team'][$activeId];
    $wild =& $state['wild'];
    if((int)$player['hp']<=0 || (int)$wild['hp']<=0) return;

    $moves=$wild['moves'];
    $damaging=[];
    foreach($moves as $m){
        $md=pv_wild_move_data($db,(string)$m,(string)$wild['type1']);
        if((int)$md['power']>0) $damaging[]=$m;
    }
    $pool=$damaging ?: $moves;
    $moveName=(string)$pool[random_int(0,count($pool)-1)];
    $move=pv_wild_move_data($db,$moveName,(string)$wild['type1']);
    $result=pv_wild_damage($wild,$player,$move);
    $state['fx']['enemy']=[
        'move'=>(string)$move['attack'],'type'=>(string)$move['type'],'hit'=>(bool)$result['hit'],
        'damage'=>(int)$result['damage'],'critical'=>(bool)$result['critical'],'effectiveness'=>(float)$result['effectiveness'],
    ];
    if(!$result['hit']) {
        pv_wild_log($state,'Wild '.$wild['display_name'].' used '.$move['attack'].', but it missed.','muted');
    } else {
        $player['hp']=max(0,(int)$player['hp']-(int)$result['damage']);
        $msg='Wild '.$wild['display_name'].' used '.$move['attack'].' and dealt '.(int)$result['damage'].' damage.';
        if($result['critical']) $msg.=' Critical hit!';
        $msg.=pv_wild_effectiveness_text((float)$result['effectiveness']);
        pv_wild_log($state,$msg,$result['effectiveness']>=2?'danger':'neutral');
    }

    if((int)$player['hp']<=0){
        $state['fx']['player_fainted']=true;
        pv_wild_log($state,$player['name'].' fainted.','danger');
        foreach($state['team'] as $id=>$member){
            if((int)$member['hp']>0){
                $state['active_id']=(int)$id;
                $state['fx']['auto_switch']=['name'=>(string)$member['name'],'pokemon_id'=>(int)$id];
                $state['participants'][(int)$id]=true;
                pv_wild_log($state,$member['name'].' entered the battle.','accent');
                return;
            }
        }
        pv_wild_finalize_loss($db,$state);
    }
}

function pv_wild_finalize_win(mysqli $db, array &$state): void
{
    if (($state['status'] ?? '') !== 'active' || !empty($state['rewarded'])) return;
    $uid=(int)$_SESSION['myid'];
    $battleId=(string)($state['id'] ?? '');

    // If a prior request committed the reward but the browser lost the response,
    // rebuild the session result from the durable ledger instead of paying twice.
    $existing=pv_wild_result_row($db,$battleId,$uid);
    if($existing && (string)$existing['outcome']==='won'){
        $state['status']='won';$state['rewarded']=true;
        $state['result']=['title'=>'Battle won','message'=>'Wild '.$state['wild']['display_name'].' was defeated.','exp'=>(int)$existing['reward_exp'],'money'=>(int)$existing['reward_money']];
        pv_wild_log($state,'Your battle result has been restored.','good');
        return;
    }
    if($existing) throw new RuntimeException('This encounter has already been resolved. Return to the map to continue exploring.');

    $wildLevel=max(1,(int)$state['wild']['level']);
    $exp=max(75,$wildLevel*55);
    $money=max(50,$wildLevel*22+random_int(25,125));
    $participantIds=array_map('intval',array_keys(array_filter($state['participants'])));

    $db->begin_transaction();
    try {
        pv_wild_result_insert($db,$state,$uid,'won',$exp,$money,0);
        $stmt=$db->prepare('UPDATE members SET battle=battle+1,money=money+? WHERE id=?');
        if(!$stmt) throw new RuntimeException('Could not record battle rewards.');
        $stmt->bind_param('ii',$money,$uid); $stmt->execute(); $stmt->close();
        foreach($participantIds as $id){
            $stmt=$db->prepare('UPDATE pokemon SET lvl=LEAST(100,GREATEST(1,FLOOR((exp+?)/500))), exp=exp+? WHERE id=? AND CAST(owner AS UNSIGNED)=?');
            if(!$stmt) throw new RuntimeException('Could not record Pokémon experience.');
            $stmt->bind_param('iiii',$exp,$exp,$id,$uid); $stmt->execute(); $stmt->close();
            $stmt=$db->prepare('UPDATE pokemon_stats SET happiness=LEAST(255,happiness+1) WHERE id=?');
            if($stmt){$stmt->bind_param('i',$id);$stmt->execute();$stmt->close();}
        }
        $db->commit();
    } catch(Throwable $e){
        $db->rollback();
        // Duplicate-key races are recoverable if another request already made
        // the exact same battle durable.
        $existing=pv_wild_result_row($db,$battleId,$uid);
        if($existing && (string)$existing['outcome']==='won'){
            $state['status']='won';$state['rewarded']=true;
            $state['result']=['title'=>'Battle won','message'=>'Wild '.$state['wild']['display_name'].' was defeated.','exp'=>(int)$existing['reward_exp'],'money'=>(int)$existing['reward_money']];
            return;
        }
        pv_log('Wild battle reward failure: '.$e->getMessage());
        throw new RuntimeException('The battle ended, but the rewards could not be saved. Please try again from the current battle screen.');
    }
    try { pv_recalculate_trainer_progress($db,$uid,true); }
    catch(Throwable $e){ pv_log('Wild battle progress refresh failed after committed win: '.$e->getMessage()); }
    $state['status']='won'; $state['rewarded']=true;
    $state['result']=['title'=>'Battle won','message'=>'Wild '.$state['wild']['display_name'].' was defeated.','exp'=>$exp,'money'=>$money];
    pv_wild_log($state,'Wild '.$state['wild']['display_name'].' fainted. You won the battle!','good');
    pv_wild_log($state,'Battle rewards: '.$exp.' EXP for each participating Pokémon and ₽'.number_format($money).'.','good');
}

function pv_wild_finalize_loss(mysqli $db, array &$state): void
{
    if (($state['status'] ?? '') !== 'active') return;
    $uid=(int)$_SESSION['myid'];
    $battleId=(string)($state['id'] ?? '');
    $existing=pv_wild_result_row($db,$battleId,$uid);
    if($existing){
        if((string)$existing['outcome']==='lost'){
            $state['status']='lost';
            $state['result']=['title'=>'Battle lost','message'=>'Your team was defeated by wild '.$state['wild']['display_name'].'.','exp'=>0,'money'=>0];
            return;
        }
        throw new RuntimeException('This encounter has already been resolved.');
    }
    $db->begin_transaction();
    try{
        pv_wild_result_insert($db,$state,$uid,'lost',0,0,0);
        $stmt=$db->prepare('UPDATE members SET losses=losses+1 WHERE id=?');
        if(!$stmt) throw new RuntimeException('Could not record the battle result.');
        $stmt->bind_param('i',$uid);$stmt->execute();$stmt->close();
        $db->commit();
    }catch(Throwable $e){
        $db->rollback();
        $existing=pv_wild_result_row($db,$battleId,$uid);
        if(!$existing || (string)$existing['outcome']!=='lost'){
            pv_log('Wild battle defeat ledger failure: '.$e->getMessage());
            throw new RuntimeException('The battle result could not be saved. Return to the map and try again.');
        }
    }
    $state['status']='lost';
    $state['result']=['title'=>'Battle lost','message'=>'Your team was defeated by wild '.$state['wild']['display_name'].'.','exp'=>0,'money'=>0];
    pv_wild_log($state,'Your team can no longer battle. Return to the map and regroup.','danger');
}

