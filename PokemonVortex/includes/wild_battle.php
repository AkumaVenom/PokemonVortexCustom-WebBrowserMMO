/**
 * Return the exact level generated by the authoritative map encounter.
 *
 * Region worlds legitimately use early-game levels below 5. Never coerce a
 * valid encounter upward here: the level shown by the scanner must be the
 * same level used for battle HP/damage, capture creation and the result
 * ledger. The v25.2.1 progression contract caps wild encounters at level 24;
 * stale or corrupt pending encounters above that cap fail closed and must be rescanned
 * instead of being silently altered after the scanner has shown a different level.
 */
function pv_wild_authoritative_encounter_level(array $pending): int
{
    if (!array_key_exists('level', $pending)) {
        throw new RuntimeException('The wild encounter level is missing. Return to the map and scan again.');
    }
    $level = (int)$pending['level'];
    if ($level < 1 || $level > PV_WILD_LEVEL_CAP) {
        throw new RuntimeException('The wild encounter level is invalid. Return to the map and scan again.');
    }
    return $level;
}

function pv_wild_result_row(mysqli $db, string $battleId, int $uid): ?array
{
    if ($battleId === '' || $uid <= 0) return null;
    $stmt = $db->prepare('SELECT battle_id,user_id,outcome,wild_pid,wild_name,wild_level,reward_exp,reward_money,captured_pokemon_id,created_at FROM wild_battle_results WHERE battle_id=? AND user_id=? LIMIT 1');
    if (!$stmt) return null;
    $stmt->bind_param('si', $battleId, $uid);
    $stmt->execute();
    $row = $stmt->get_result()->fetch_assoc();
    $stmt->close();
    return $row ?: null;
}

function pv_wild_result_insert(mysqli $db, array $state, int $uid, string $outcome, int $rewardExp = 0, int $rewardMoney = 0, int $capturedPokemonId = 0): void
{
    $battleId = (string)($state['id'] ?? '');
    $wild = (array)($state['wild'] ?? []);
    $pid = (int)($wild['pid'] ?? 0);
    $name = (string)($wild['display_name'] ?? $wild['name'] ?? 'Wild Pokémon');
    $level = max(1, (int)($wild['level'] ?? 1));
    $createdAt = time();
    $stmt = $db->prepare('INSERT INTO wild_battle_results (battle_id,user_id,outcome,wild_pid,wild_name,wild_level,reward_exp,reward_money,captured_pokemon_id,created_at) VALUES (?,?,?,?,?,?,?,?,?,?)');
    if (!$stmt) { pv_log('Wild battle ledger prepare failed: ' . $db->error); throw new RuntimeException('Battle records are temporarily unavailable. Return to the map and try again.'); }
    $stmt->bind_param('sisisiiiii', $battleId, $uid, $outcome, $pid, $name, $level, $rewardExp, $rewardMoney, $capturedPokemonId, $createdAt);
    if (!$stmt->execute()) {
        $message = $stmt->error;
        $stmt->close();
        pv_log('Wild battle ledger insert failed: ' . $message);
        throw new RuntimeException('The battle result could not be saved. Please retry from the current battle screen.');
    }
    $stmt->close();
}

function pv_wild_hp_max(string $name, int $level, int $hpIv = 0): int
{
    $level = max(1, min(100, $level));
    $bonus = stripos($name, 'Shiny ') === 0 ? $level : 0;
    return max(20, ($level * 4) + $bonus + intdiv(max(0, min(31, $hpIv)), 2));
}

