function pv_wild_throw_ball(mysqli $db, array &$state, string $ball): void
{
    $catalog=pv_wild_ball_catalog();
    if(!isset($catalog[$ball])) throw new RuntimeException('Choose a valid Poké Ball.');
    $uid=(int)$_SESSION['myid'];
    $battleId=(string)($state['id'] ?? '');
    $existing=pv_wild_result_row($db,$battleId,$uid);
    if($existing){
        if((string)$existing['outcome']==='captured'){
            $state['status']='captured';
            $state['result']=['title'=>'Pokémon captured','message'=>$state['wild']['display_name'].' was captured.','pokemon_id'=>(int)$existing['captured_pokemon_id'],'exp'=>0,'money'=>0];
            return;
        }
        throw new RuntimeException('This encounter has already been resolved.');
    }

    $caught=false;$pokemonId=0;
    $db->begin_transaction();
    try {
        if(!pv_wild_consume($db,$uid,$catalog[$ball]['column'])) throw new RuntimeException('You do not have that Poké Ball in your inventory.');
        $wild=$state['wild'];
        $hpRatio=max(0.0,min(1.0,(float)$wild['hp']/max(1,(int)$wild['max_hp'])));
        $missing=1.0-$hpRatio;
        $levelPenalty=max(0.0,((int)$wild['level']-25)*0.003);
        $chance=(float)$catalog[$ball]['base'];
        if($chance<1.0) $chance=max(0.08,min(0.95,$chance+($missing*0.48)-$levelPenalty));
        $caught=$chance>=1.0 || (random_int(1,10000)/10000)<=$chance;
        if($caught){
            $pokemonId=pv_wild_capture_create($db,$state,$ball);
            pv_wild_result_insert($db,$state,$uid,'captured',0,0,$pokemonId);
        }
        $db->commit();
    } catch(Throwable $e){
        $db->rollback();
        $existing=pv_wild_result_row($db,$battleId,$uid);
        if($existing && (string)$existing['outcome']==='captured'){
            $caught=true;$pokemonId=(int)$existing['captured_pokemon_id'];
        }else{
            if($e instanceof RuntimeException) throw $e;
            pv_log('Wild capture failure: '.$e->getMessage());
            throw new RuntimeException('The capture could not be completed. Please try again.');
        }
    }

    $state['fx']['capture']=['ball'=>$ball,'caught'=>$caught];
    if($caught){
        try { pv_recalculate_trainer_progress($db,$uid,true); }
        catch(Throwable $e){ pv_log('Wild capture progress refresh failed after committed capture: '.$e->getMessage()); }
        $state['status']='captured';
        $state['result']=['title'=>'Pokémon captured','message'=>$state['wild']['display_name'].' was caught with a '.$ball.'!','pokemon_id'=>$pokemonId,'exp'=>0,'money'=>0];
        pv_wild_log($state,'Click… click… caught! Wild '.$state['wild']['display_name'].' joined your collection.','good');
    } else {
        pv_wild_log($state,'You threw a '.$ball.', but wild '.$state['wild']['display_name'].' broke free.','danger');
        pv_wild_enemy_turn($db,$state);
    }
}

function pv_wild_switch(mysqli $db, array &$state, int $pokemonId): void
{
    if(!isset($state['team'][$pokemonId])) throw new RuntimeException('That Pokémon is not in this battle team.');
    if((int)$state['team'][$pokemonId]['hp']<=0) throw new RuntimeException('A fainted Pokémon cannot be switched in.');
    if($pokemonId===(int)$state['active_id']) throw new RuntimeException('That Pokémon is already active.');
    $state['active_id']=$pokemonId;$state['participants'][$pokemonId]=true;
    $state['fx']['switch']=['pokemon_id'=>$pokemonId,'name'=>(string)$state['team'][$pokemonId]['name']];
    pv_wild_log($state,'Go, '.$state['team'][$pokemonId]['name'].'!','accent');
    pv_wild_enemy_turn($db,$state);
}

function pv_wild_handle_action(mysqli $db, array $state, array $post): array
{
    if(($state['status']??'')!=='active') return $state;
    $submittedTurn=(int)($post['battle_turn']??0);
    $currentTurn=max(1,(int)($state['turn']??1));
    if($submittedTurn!==$currentTurn) throw new RuntimeException('That action came from an older turn. The current battle has been refreshed.');
    $action=(string)($post['battle_action']??'');
    $detail=match($action){
        'attack'=>trim((string)($post['move']??'')),
        'heal'=>trim((string)($post['item']??'')),
        'ball'=>trim((string)($post['ball']??'')),
        'switch'=>(string)max(0,(int)($post['pokemon_id']??0)),
        default=>'',
    };
    $state['fx']=[
        'id'=>bin2hex(random_bytes(6)),'turn'=>$currentTurn,'action'=>$action,'detail'=>$detail,
        'player'=>null,'enemy'=>null,'capture'=>null,'heal'=>null,'switch'=>null,'created_at'=>time(),
    ];
    switch($action){
        case 'attack':
            pv_wild_attack_turn($db,$state,(int)$state['active_id'],trim((string)($post['move']??'')));
            break;
        case 'heal':
            pv_wild_use_heal($db,$state,trim((string)($post['item']??'')));
            break;
        case 'ball':
            pv_wild_throw_ball($db,$state,trim((string)($post['ball']??'')));
            break;
        case 'switch':
            pv_wild_switch($db,$state,(int)($post['pokemon_id']??0));
            break;
        case 'run':
            $state['status']='ran';$state['result']=['title'=>'Battle ended','message'=>'You safely withdrew from the encounter.','exp'=>0,'money'=>0];
            pv_wild_log($state,'You escaped from wild '.$state['wild']['display_name'].'.','muted');
            break;
        default:
            throw new RuntimeException('Choose a battle action.');
    }
    $state['turn']=max(1,(int)$state['turn']+1);$state['updated_at']=time();pv_wild_save($state);return $state;
}
